const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const { buildWindowsServiceScript } = require('./service-utils.cjs')
const scripts = path.join(__dirname, '../resources/windows')
test('bundled action retains existing service operations', () => {
 const saved = fs.readFileSync(path.join(scripts, 'service-action.ps1'), 'utf8')
 const generated = buildWindowsServiceScript({ action:'start', installDir:'', targetBinary:'', targetConfig:'', outputPath:'' })
 assert.equal(saved.slice(saved.indexOf('$serviceLog =')).trim(), generated.slice(generated.indexOf('$serviceLog =')).trim())
})
test('desktop entry invokes packaged scripts instead of generated commands', () => {
 const source = fs.readFileSync(path.join(__dirname, 'main.cjs'), 'utf8')
 const action = source.slice(source.indexOf('async function runWindowsServiceAction'), source.indexOf('async function runMacServiceAction'))
 assert.match(action, /'-File', launcherPath/)
 assert.doesNotMatch(action, /EncodedCommand|buildWindowsServiceScript|buildWindowsElevationLauncher/)
 const launcher = fs.readFileSync(path.join(scripts,'service-launcher.ps1'),'utf8')
 assert.match(launcher, /-Verb RunAs/)
 assert.doesNotMatch(launcher, /EncodedCommand|Invoke-Expression/)
 const config = JSON.parse(fs.readFileSync(path.join(__dirname,'../package.json'),'utf8'))
 assert.ok(config.build.win.extraResources.some(x => x.from === 'resources/windows'))
})
test('invalid service actions are rejected before any operation', {skip:process.platform !== 'win32'}, () => {
 const os = require('node:os')
 const dir = fs.mkdtempSync(path.join(os.tmpdir(),'frp-script-test-'))
 try {
  const request = path.join(dir,'request.json')
  fs.writeFileSync(request, JSON.stringify({action:'invalid'}))
  const result = spawnSync('powershell.exe',['-NoProfile','-NonInteractive','-ExecutionPolicy','Bypass','-File',path.join(scripts,'service-action.ps1'),'-RequestPath',request],{encoding:'utf8',windowsHide:true})
  assert.notEqual(result.status,0)
  assert.match(result.stdout+result.stderr,/Unsupported service action/)
  assert.equal(fs.existsSync(path.join(dir,'service-output.txt')),false)
 } finally { fs.rmSync(dir,{recursive:true,force:true}) }
})
